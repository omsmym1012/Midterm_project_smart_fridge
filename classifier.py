# 미리 만든 목록에서 찾기
# ---------------------------------------------------------------
def _match(table, name):
    """목록(table)에서 찾는다. 정확히 같은 이름이 없으면 이름 안에 포함된 단어로 찾는다.

    예: "서울우유" → "우유", "냉동만두" → "만두"
    한국어 이름은 뒤에 오는 단어가 진짜 재료인 경우가 많아서("딸기우유" → 우유, "조미김" → 김),
    이름 끝에 붙은 단어를 먼저 고르고, 그다음 긴 단어를 고른다.
    """
    key = _normalize(name)
    if key in table:
        return table[key]
    # 한 글자 단어("무", "김", "밥")는 엉뚱하게 걸리기 쉬워서("김밥" → "김"),
    # 이름 끝에 붙어 있을 때만 쓴다. ("조미김" → "김", "가래떡" → "떡")
    matches = [
        word for word in table
        if (len(word) >= 2 and word in key) or (len(word) == 1 and key.endswith(word))
    ]
    if matches:
        best = max(matches, key=lambda word: (key.endswith(word), len(word)))
        return table[best]
    return None


def _from_builtin(name):
    """분류 목록에서 찾는다. 반환: (종류, 보관, 단위, 팁) 또는 None"""
    return _match(BUILTIN, name)


