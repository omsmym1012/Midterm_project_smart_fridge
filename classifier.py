def classify(name):
    """재료 이름을 분류해서 dict로 돌려준다.

    반환 예: {"category": "채소", "storage": "냉장", "unit": "단", "tip": "...", "source": "builtin"}
    source: "cache"(사용자 수정·이전 AI) / "builtin"(목록) / "ai" / "default"(분류 실패)
    """
    cache = _load_cache()
    key = _normalize(name)
    builtin = _from_builtin(name)

    if key in cache:
        result = {**cache[key], "source": "cache"}
        # 단위 추천 기능 전에 저장된 기록에는 단위가 없으므로 목록이나 기본 단위로 채운다.
        result.setdefault("unit", builtin[2] if builtin else DEFAULT_UNIT)
        return result

    if builtin:
        category, storage, unit, tip = builtin
        if "냉동" in key:
            storage = "냉동"  # "냉동블루베리"처럼 이름에 냉동이 붙으면 보관 방법도 냉동
        return {"category": category, "storage": storage, "unit": unit, "tip": tip, "source": "builtin"}

    found = _ask_ai(name)
    if found:
        category, storage, unit, tip, zone = found
        # AI 결과는 저장해 두고 다음에는 다시 묻지 않는다.
        cache[key] = {"category": category, "storage": storage, "unit": unit, "tip": tip, "zone": zone}
        _save_cache(cache)
        return {"category": category, "storage": storage, "unit": unit, "tip": tip, "source": "ai"}

    return {
        "category": DEFAULT_CATEGORY, "storage": DEFAULT_STORAGE,
        "unit": DEFAULT_UNIT, "tip": "", "source": "default",
    }


def name_zone(name, cache=None):
    """재료 이름으로 추천 칸 id를 찾는다. (AI는 부르지 않는다)

    캐시(예전 AI 결과) → 목록(BUILTIN_ZONE) 순서로 찾고, 없으면 None.
    여러 재료를 한 번에 찾을 때는 cache를 미리 읽어서 넘기면 파일을 여러 번 읽지 않는다.
    """
    cache = _load_cache() if cache is None else cache
    zone = cache.get(_normalize(name), {}).get("zone")
    return zone if zone in ZONES else _match(BUILTIN_ZONE, name)


def load_cache():
    """캐시를 한 번 읽어 둘 때 쓴다. (name_zone에 넘기기용)"""
    return _load_cache()
